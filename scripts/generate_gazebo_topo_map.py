#!/usr/bin/env python3
"""Emit the test_world road graph using WGS84 LLA <-> ECEF <-> ENU.

No dependencies beyond Python's standard library. Output goes to stdout; use
--check to verify the checked-in map and collision clearance against the world.
"""
import argparse
import math
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = (30.8277361671667, 120.847804830667, 3.2133)
A = 6378137.0
F = 1.0 / 298.257223563
E2 = F * (2.0 - F)
# Manual centerline waypoints in the default test_world.world, metres east/north.
# A stem from spawn leads into the western room, then an eastern loop offers
# two routes around the obstacles. These are NOT for hui_path.world.
POINTS = [(0, 0), (-5, 1), (-10, 5), (-11, 10), (-6, 12), (-2, 12),
          (0, 14), (5, 13), (9, 13), (15, 13), (21, 13), (27, 13),
          (27, 8), (24, 9), (20, 8), (16, 8), (12, 8), (9, 8), (9, 11)]
EDGES = [(i, i + 1) for i in range(len(POINTS) - 1)] + [(18, 8)]
# Deliberately narrow teaching doorways: (centre x, centre y, half opening).
# The centreline runs straight through each one, so the general 0.60 m
# clearance rule cannot apply inside the opening; there the check uses the
# real half opening instead.
NARROW_GATES = [(10.5, 8.0, 0.35)]
GATE_WINDOW_X = 0.75


def lla_to_ecef(lat, lon, alt):
    lat, lon = math.radians(lat), math.radians(lon)
    n = A / math.sqrt(1 - E2 * math.sin(lat) ** 2)
    return ((n + alt) * math.cos(lat) * math.cos(lon),
            (n + alt) * math.cos(lat) * math.sin(lon),
            (n * (1 - E2) + alt) * math.sin(lat))


def ecef_to_lla(x, y, z):
    p = math.hypot(x, y)
    lat = math.atan2(z, p * (1 - E2))
    for _ in range(15):
        n = A / math.sqrt(1 - E2 * math.sin(lat) ** 2)
        next_lat = math.atan2(z + E2 * n * math.sin(lat), p)
        if abs(next_lat - lat) < 1e-15:
            lat = next_lat
            break
        lat = next_lat
    n = A / math.sqrt(1 - E2 * math.sin(lat) ** 2)
    alt = p / math.cos(lat) - n
    return math.degrees(lat), math.degrees(math.atan2(y, x)), alt


def enu_basis():
    lat, lon = map(math.radians, ORIGIN[:2])
    return ((-math.sin(lon), math.cos(lon), 0),
            (-math.sin(lat) * math.cos(lon), -math.sin(lat) * math.sin(lon), math.cos(lat)),
            (math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat)))


def enu_to_lla(east, north, up=0.0):
    origin = lla_to_ecef(*ORIGIN)
    basis = enu_basis()
    xyz = [origin[j] + sum(v * row[j] for v, row in zip((east, north, up), basis))
           for j in range(3)]
    return ecef_to_lla(*xyz)


def lla_to_enu(lat, lon, alt):
    delta = [v - o for v, o in zip(lla_to_ecef(lat, lon, alt), lla_to_ecef(*ORIGIN))]
    return tuple(sum(v * d for v, d in zip(row, delta)) for row in enu_basis())


def render():
    lines = ['# Generated by scripts/generate_gazebo_topo_map.py; test_world.world',
             'map:', '0 gazebo_test_world', 'lla_mode:', '1', 'origin:',
             ' '.join(format(v, '.15g') for v in ORIGIN), 'node:',
             '# id type mapId east north up latitude longitude altitude']
    error = 0.0
    for i, (x, y) in enumerate(POINTS):
        encoded = [format(v, '.15g') for v in enu_to_lla(x, y)]
        restored = lla_to_enu(*map(float, encoded))
        error = max(error, math.dist(restored, (x, y, 0)))
        lines.append(f'{i} 0 0 {x} {y} 0 ' + ' '.join(encoded))
    assert error < 1e-6, f'WGS84 round-trip error {error} m'
    lines.extend(['edge:', '# id type mapId from to obt; type=0 is bidirectional'])
    lines.extend(f'{i} 0 0 {a} {b} 0' for i, (a, b) in enumerate(EDGES))
    return '\n'.join(lines) + '\n', error


def pose(element):
    if element.find('pose') is not None and element.find('pose').get('relative_to'):
        raise ValueError('relative_to poses require an SDF frame resolver')
    values = list(map(float, element.findtext('pose', '0 0 0 0 0 0').split()))
    pitched = abs(values[3]) > 1e-9 or abs(values[4]) > 1e-9
    return values[0], values[1], values[5], pitched


def compose(parent, child):
    x, y, yaw = parent
    u, v, angle = child
    return x + math.cos(yaw)*u - math.sin(yaw)*v, y + math.sin(yaw)*u + math.cos(yaw)*v, yaw + angle


def validate_world(path):
    """Conservative planar clearance, including wall thickness and obstacle radii.

    Pitched (roll/pitch) geometry is a traversable ramp - e.g. the
    slope_15deg_hill in test_world.world, which the global route intentionally
    drives over - so it is reported but excluded from the blocking clearance.
    """
    world = ET.parse(path).getroot().find('world')
    shapes = []
    ramps = []
    for model in world.findall('model'):
        for link in model.findall('link'):
            for collision in link.findall('collision'):
                model_pose, link_pose, collision_pose = pose(model), pose(link), pose(collision)
                frame = compose(compose(model_pose[:3], link_pose[:3]), collision_pose[:3])
                geom = collision.find('geometry')
                if geom.find('plane') is not None:
                    continue
                name = model.get('name') + '/' + link.get('name')
                if any(p[3] for p in (model_pose, link_pose, collision_pose)):
                    ramps.append(name)
                    continue
                if geom.find('box') is not None:
                    size = list(map(float, geom.findtext('box/size').split()))
                    shape = ('box', size[0]/2, size[1]/2)
                elif geom.find('cylinder') is not None:
                    shape = ('circle', float(geom.findtext('cylinder/radius')), 0)
                elif geom.find('sphere') is not None:
                    shape = ('circle', float(geom.findtext('sphere/radius')), 0)
                else:
                    raise ValueError(f'Unsupported collision geometry in {model.get("name")}')
                shapes.append((frame, shape, name))
    assert shapes, 'No obstacles were checked'
    minimum = float('inf')
    for a, b in EDGES:
        start, end = POINTS[a], POINTS[b]
        count = math.ceil(math.dist(start, end) / 0.025)
        for i in range(count + 1):
            x, y = [s + (e-s)*i/count for s, e in zip(start, end)]
            for (cx, cy, yaw), (kind, sx, sy), name in shapes:
                dx, dy = x-cx, y-cy
                u, v = math.cos(yaw)*dx + math.sin(yaw)*dy, -math.sin(yaw)*dx + math.cos(yaw)*dy
                distance = (math.hypot(max(abs(u)-sx, 0), max(abs(v)-sy, 0))
                            if kind == 'box' else math.hypot(u, v)-sx)
                minimum = min(minimum, distance)
                # 0.60 m clearance exceeds the configured 0.391 m footprint radius,
                # even allowing for the 0.0125 m sampling error. A teaching doorway
                # is the one place where the route must thread the opening itself,
                # so the limit falls back to the real half opening there.
                limit = 0.60
                for gx, gy, half_gap in NARROW_GATES:
                    if abs(x - gx) <= GATE_WINDOW_X and abs(y - gy) <= half_gap:
                        limit = min(limit, half_gap - 0.015)
                assert distance >= limit, f'Edge {a}->{b} too close to {name}: {distance:.3f} m'
    return minimum, sorted(set(ramps))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--world', type=Path,
                        default=ROOT / 'src/gazebo_sim/vehicle_gazebo_sim/worlds/test_world.world')
    args = parser.parse_args()
    content, error = render()
    clearance, ramps = validate_world(args.world)
    ramp_note = f'; traversable ramps skipped: {", ".join(ramps)}' if ramps else ''
    print(f'{len(POINTS)} nodes, {len(EDGES)} edges; round-trip={error:.3g} m; '
          f'minimum sampled clearance={clearance:.3f} m{ramp_note}', file=sys.stderr)
    if args.check:
        actual = (ROOT / 'src/robot_launch/maps/topo_map_gazebo.yaml').read_text()
        assert actual == content, 'Checked-in map differs from generator output'
    else:
        print(content, end='')


if __name__ == '__main__':
    main()
